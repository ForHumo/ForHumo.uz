export type EsT = (key: string, fallback?: string) => string;

export function useEsT(): EsT {
    const locale = useLocale();
    const i = locale === "ru" ? 1 : locale === "en" ? 2 : 0;
    return (key: string, fallback?: string) => {
        const e = DICT[key];
        return e ? e[i] : (fallback ?? key);
    };
}
